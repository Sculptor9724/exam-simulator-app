-- Verified against the user-provided schema-only export on 2026-11-02.
-- Intended for the fresh-install chain, not a blanket production repair.
BEGIN;
ALTER TABLE public.waitlist ADD COLUMN sent_invite boolean DEFAULT false;
ALTER TABLE public.exams ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE public.user_data RENAME CONSTRAINT user_data_pkey TO user_profiles_pkey;
CREATE TRIGGER update_user_profiles_updated_at
  BEFORE UPDATE ON public.user_data
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();
ALTER EXTENSION pgcrypto SET SCHEMA extensions;

-- Match the observed log write scope: owners may insert/update, not delete logs.
DROP POLICY "Owner manages exam logs" ON public.exam_logs;
CREATE POLICY "Users can view their own exam logs" ON public.exam_logs
  FOR SELECT TO authenticated USING (user_id = auth.uid());
CREATE POLICY "Users can insert their own exam logs" ON public.exam_logs
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());
CREATE POLICY "User can update own row" ON public.exam_logs
  FOR UPDATE TO authenticated USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

-- The exported ratings policy permits insertion, not client editing/deletion.
-- Keep owner and exam-owner reads needed by the frontend's feedback display.
DROP POLICY "Owner manages exam ratings" ON public.exam_ratings;
CREATE POLICY "Users can insert their own exam ratings" ON public.exam_ratings
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());
CREATE POLICY "Users can view their own exam ratings" ON public.exam_ratings
  FOR SELECT TO authenticated USING (user_id = auth.uid());

-- Supabase may supply broad default grants, including TRUNCATE (not filtered by
-- RLS). Set explicit privileges rather than assuming a blank-role test runtime.
REVOKE ALL ON TABLE public.profiles, public.classes, public.exams,
  public.exam_logs, public.exam_ratings, public.class_memberships, public.class_exams,
  public.user_data, public.waitlist, public.budget_status, public.signup_allowed_emails
  FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.profiles, public.classes, public.exams,
  public.class_memberships, public.class_exams TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.exam_logs TO authenticated;
GRANT SELECT, INSERT ON public.exam_ratings TO authenticated;
-- A browser may submit an email, not set the server-maintained invitation flag.
GRANT INSERT (email) ON public.waitlist TO anon, authenticated;
GRANT ALL ON TABLE public.profiles, public.classes, public.exams,
  public.exam_logs, public.exam_ratings, public.class_memberships, public.class_exams,
  public.user_data, public.waitlist, public.budget_status, public.signup_allowed_emails
  TO service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;
COMMIT;
