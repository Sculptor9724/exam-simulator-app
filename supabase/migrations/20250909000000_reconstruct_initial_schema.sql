-- Reconstructed prerequisite schema for NEW installations only.
-- Evidence: supabase-schema.sql and the earlier SQL under thoughts/shared/lol/.
-- This is not a dump of the live database. Never blindly push it to an existing DB.
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA extensions;

CREATE TABLE public.profiles (
  id uuid NOT NULL DEFAULT extensions.uuid_generate_v4(),
  user_id uuid NOT NULL UNIQUE,
  full_name text,
  school text,
  education_name text,
  semester integer,
  is_student boolean DEFAULT false,
  role text DEFAULT 'student'::text,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT profiles_pkey PRIMARY KEY (id),
  CONSTRAINT profiles_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id)
);
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.classes (
  id uuid NOT NULL DEFAULT extensions.uuid_generate_v4(),
  user_id uuid NOT NULL,
  title text NOT NULL,
  description text,
  schoolname text,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT classes_pkey PRIMARY KEY (id),
  CONSTRAINT classes_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id)
);
ALTER TABLE public.classes ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.exams (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  title text,
  description text,
  type text,
  duration integer,
  grade_criteria text,
  feedback text,
  learning_goals text,
  typical_questions text,
  is_public boolean,
  user_id uuid,
  CONSTRAINT exams_pkey PRIMARY KEY (id),
  CONSTRAINT exams_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id)
);
ALTER TABLE public.exams ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.exam_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid,
  exam_id bigint,
  created_at timestamp with time zone DEFAULT now(),
  finished_at timestamp with time zone,
  finished_reason text,
  grade text,
  feedback text,
  CONSTRAINT exam_logs_pkey PRIMARY KEY (id),
  CONSTRAINT exam_logs_exam_id_fkey FOREIGN KEY (exam_id) REFERENCES public.exams(id),
  CONSTRAINT exam_logs_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id)
);
ALTER TABLE public.exam_logs ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.exam_ratings (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  exam_id bigint NOT NULL,
  user_id uuid NOT NULL,
  rating smallint NOT NULL CHECK (rating >= 0 AND rating <= 5),
  good_feedback text,
  improve_feedback text,
  created_at timestamp with time zone DEFAULT now(),
  CONSTRAINT exam_ratings_pkey PRIMARY KEY (id),
  CONSTRAINT exam_ratings_exam_id_fkey FOREIGN KEY (exam_id) REFERENCES public.exams(id),
  CONSTRAINT exam_ratings_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id)
);
ALTER TABLE public.exam_ratings ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.user_data (
  id uuid NOT NULL,
  full_name text,
  school text,
  education_name text,
  semester integer,
  is_student boolean DEFAULT false,
  is_manually_activated boolean DEFAULT false,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT user_data_pkey PRIMARY KEY (id),
  CONSTRAINT user_profiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id)
);
ALTER TABLE public.user_data ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (user_id, full_name, school, education_name, semester, is_student)
  VALUES (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'school',
    new.raw_user_meta_data->>'education_name',
    NULLIF(new.raw_user_meta_data->>'semester', '')::INTEGER,
    (new.raw_user_meta_data->>'is_student')::BOOLEAN
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- Create a trigger to call the function when a new user is created
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Allow teachers to view their own classes
CREATE POLICY "Teachers can view their own classes"
ON public.classes FOR SELECT
USING ( auth.uid() = user_id );

-- Allow teachers to insert their own classes
CREATE POLICY "Teachers can create classes"
ON public.classes FOR INSERT
WITH CHECK ( auth.uid() = user_id );

-- Allow teachers to update their own classes
CREATE POLICY "Teachers can update their own classes"
ON public.classes FOR UPDATE
USING ( auth.uid() = user_id )
WITH CHECK ( auth.uid() = user_id );

-- Allow teachers to delete their own classes
CREATE POLICY "Teachers can delete their own classes"
ON public.classes FOR DELETE
USING ( auth.uid() = user_id );

-- Create updated_at trigger
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ language 'plpgsql';

CREATE TRIGGER update_classes_updated_at BEFORE UPDATE
ON classes FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- Conservative owner policies reconstructed for tables missing from migrations.
-- Additional teacher/class access is added by the later migrations.
CREATE POLICY "Baseline profile read" ON public.profiles FOR SELECT TO authenticated
  USING (user_id = auth.uid());
CREATE POLICY "Baseline profile update" ON public.profiles FOR UPDATE TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
CREATE POLICY "Owner manages exams" ON public.exams FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
CREATE POLICY "Read public exams" ON public.exams FOR SELECT TO authenticated
  USING (is_public IS TRUE);
CREATE POLICY "Owner manages exam logs" ON public.exam_logs FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
CREATE POLICY "Owner manages exam ratings" ON public.exam_ratings FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
-- Legacy user_data is retained for the account-deletion migration; client access
-- stays denied by RLS. Current frontend uses profiles instead.
CREATE INDEX idx_exam_logs_finished_at ON public.exam_logs(finished_at);
CREATE INDEX idx_exam_logs_user_id ON public.exam_logs(user_id);
CREATE INDEX idx_exam_logs_exam_id ON public.exam_logs(exam_id);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.profiles, public.classes,
  public.exams, public.exam_logs, public.exam_ratings TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
